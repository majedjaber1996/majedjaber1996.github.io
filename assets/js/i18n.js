const reverseTranslations = Object.fromEntries(Object.entries(translations).map(([english, french]) => [french, english]));
const store = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* ignore */ } }
};

export function getLocale() {
  return store.get('mj-language') === 'fr' ? 'fr' : 'en';
}

export function localizeData(value, locale) {
  if (locale === 'en') return structuredClone(value);
  if (Array.isArray(value)) return value.map((item) => localizeData(item, locale));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeData(item, locale)]));
  }
  return typeof value === 'string' ? (translations[value] || value) : value;
}

function translateValue(value, locale) {
  if (typeof value !== 'string') return value;
  return locale === 'fr' ? (translations[value] || value) : (reverseTranslations[value] || value);
}

export function translateDocument(locale) {
  document.documentElement.lang = locale;
  document.title = translateValue(document.title, locale);
  const source = locale === 'fr' ? translations : reverseTranslations;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (node.parentElement?.closest('script, style, noscript')) return;
    const value = node.nodeValue;
    const trimmed = value.trim();
    const normalized = trimmed.replace(/\s+/g, ' ');
    if (!normalized || !source[normalized]) return;
    node.nodeValue = value.replace(trimmed, source[normalized]);
  });

  document.querySelectorAll('[placeholder], [title], [aria-label]').forEach((el) => {
    ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
      if (el.hasAttribute(attribute)) el.setAttribute(attribute, translateValue(el.getAttribute(attribute), locale));
    });
  });
}

export function initLanguage() {
  const button = document.getElementById('languageToggle');
  if (!button) return;
  const locale = getLocale();
  button.textContent = locale === 'fr' ? 'EN' : 'FR';
  button.setAttribute('aria-label', locale === 'fr' ? 'Passer en anglais' : 'Switch to French');
  button.setAttribute('title', locale === 'fr' ? 'Passer en anglais' : 'Switch to French');
  button.addEventListener('click', () => {
    store.set('mj-language', locale === 'fr' ? 'en' : 'fr');
    window.location.reload();
  });
}
